// Generates src/lib/errors-map.ts from analysis/synthesis.json. Run from frontend/:
//   node scripts/gen-errors-map.mjs ../analysis/synthesis.json src/lib/errors-map.ts
// The output is bundled for the browser, so every dashed SSN in the source text is masked to its last 4.
import { readFileSync, writeFileSync } from 'node:fs'

const [src, out] = process.argv.slice(2)
const s = JSON.parse(readFileSync(src, 'utf8'))
const masked = (v) => String(v).replace(/\b\d{3}-\d{2}-(\d{4})\b/g, '•••-••-$1')
const q = (v) => `'${masked(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n')}'`
const arr = (xs) => `[${xs.map(q).join(', ')}]`
const num = (v) => (typeof v === 'number' ? String(v) : 'null')

const checks = s.checks.checks
const uncaught = Object.fromEntries(s.checks.uncaught.map((u) => [u.slice(0, u.indexOf(':')), u.slice(u.indexOf(':') + 1).trim()]))

const lines = []
lines.push('// GENERATED by scripts/gen-errors-map.mjs from analysis/synthesis.json (dashed SSNs masked). Do not edit by hand.')
lines.push('// canon.errors (id, title, category, severity, area, tax effects, how_surfaced, refs, affected_lines) joined with')
lines.push('// checks.checks[].catches (which catalog checks catch each error) and checks.uncaught. Static: live status comes')
lines.push('// from model.findings at runtime (src/components/handin/errors-rows.ts).')
lines.push('')
lines.push("export type ErrorCategory =")
const cats = [...new Set(s.canon.errors.map((e) => e.category))].sort()
lines.push(cats.map((c) => `  | ${q(c)}`).join('\n'))
lines.push('')
lines.push('export interface CanonError {')
lines.push('  id: string')
lines.push('  title: string')
lines.push('  category: ErrorCategory')
lines.push("  severity: 'high' | 'medium' | 'low'")
lines.push('  area: string')
lines.push('  /** Tax effect against v3 (null: not priced). */')
lines.push('  fed: number | null')
lines.push('  ca: number | null')
lines.push('  howSurfaced: string')
lines.push('  /** Catalog checks whose `catches` include this error. */')
lines.push('  checks: string[]')
lines.push('  /** Packet refs the error rests on, then the return lines it affects. */')
lines.push('  refs: string[]')
lines.push('  lines: string[]')
lines.push('  /** Why no check can decide it (checks.uncaught). */')
lines.push('  uncaught?: string')
lines.push('}')
lines.push('')
lines.push('/** Every catalog check: id → name (implemented or not). */')
lines.push('export const CHECK_NAMES: Record<string, string> = {')
for (const c of checks) lines.push(`  ${q(c.id)}: ${q(c.name)},`)
lines.push('}')
lines.push('')
lines.push('export const CANON_ERRORS: CanonError[] = [')
for (const e of s.canon.errors) {
  const by = checks.filter((c) => c.catches.includes(e.id)).map((c) => c.id)
  lines.push('  {')
  lines.push(`    id: ${q(e.id)}, category: ${q(e.category)}, severity: ${q(e.severity)},`)
  lines.push(`    title: ${q(e.title)},`)
  lines.push(`    area: ${q(e.area)},`)
  lines.push(`    fed: ${num(e.tax_effect_federal)}, ca: ${num(e.tax_effect_california)},`)
  lines.push(`    howSurfaced: ${q(e.how_surfaced)},`)
  lines.push(`    checks: ${arr(by)},`)
  lines.push(`    refs: ${arr(e.refs)},`)
  lines.push(`    lines: ${arr(e.affected_lines)},`)
  if (uncaught[e.id]) lines.push(`    uncaught: ${q(uncaught[e.id])},`)
  lines.push('  },')
}
lines.push(']')
lines.push('')
writeFileSync(out, lines.join('\n'))
console.log(`wrote ${s.canon.errors.length} errors, ${checks.length} checks`)
